#!/usr/bin/env python3
"""Turns pw_runtime.h into runtime_embedded.h (raw-string chunks) so codegen can
paste the runtime into every generated validator.  Run after editing pw_runtime.h:
    python3 tools/embed_runtime.py
"""
import os
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
src = open(os.path.join(root, "pw_runtime.h"), encoding="utf-8").read()
assert ')PWRT"' not in src
chunks, cur = [], ""
for line in src.splitlines(keepends=True):
    if len(cur) + len(line) > 6000:      # MSVC caps a single string literal at ~16 KB
        chunks.append(cur); cur = ""
    cur += line
chunks.append(cur)
with open(os.path.join(root, "runtime_embedded.h"), "w", encoding="utf-8") as f:
    f.write("// AUTO-GENERATED by tools/embed_runtime.py from pw_runtime.h - do not edit\n")
    f.write("#ifndef RUNTIME_EMBEDDED_H\n#define RUNTIME_EMBEDDED_H\n")
    f.write("static const char* const kRuntimeChunks[] = {\n")
    for c in chunks:
        f.write('R"PWRT(' + c + ')PWRT",\n')
    f.write("};\n#endif\n")
print("wrote runtime_embedded.h with", len(chunks), "chunks")
